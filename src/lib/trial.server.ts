// Server-only: the 14-day free trial on monthly plans.
//
// Stripe Checkout cannot combine a trial with billing_cycle_anchor ("Checkout
// doesn't support combining a trial with the billing cycle anchor",
// https://docs.stripe.com/billing/subscriptions/billing-cycle), but the
// Subscriptions API can: trial_end plus billing_cycle_anchor gives a prorated
// invoice from the trial end to the anchor, then the full price on the anchor
// day each month (same page, "Combine a trial with the billing_cycle_anchor").
//
// So the flow is:
// 1. startTrialCheckout: a Checkout Session in `setup` mode saves the card on
//    the business's Stripe customer. Nothing is charged.
// 2. The webhook gets checkout.session.completed (mode setup) and calls
//    startTrialFromSession: it reads the saved card from the SetupIntent and
//    creates the subscription with POST /v1/subscriptions:
//    trial_end = 9am UK 14 days after sign-up, billing_cycle_anchor = 9am UK on
//    the 1st after the trial ends, proration_behavior = create_prorations.
// 3. Stripe sends customer.subscription.created (status trialing), which the
//    webhook saves (trialing unlocks the paid plan) and tells HQ trial_started.
// 4. On the trial end day Stripe charges the part-month (invoice.paid), then
//    the full price on the 1st of each month.
// No em dashes in user-facing copy (AGENTS.md).
import { stripe } from "./stripe.server";
import { serviceWrite } from "./supabase-service.server";
import { londonToday, monthlyTrial } from "./billing-cycle";
import { GROWTH, MANAGED, money, planPence, TRIAL_TERMS, type CheckoutPlan } from "./shop";

const ORIGIN = "https://repsuites.com";

// Fixed Stripe product ids, so every trial subscription uses the same
// product. Products can be created with our own id ("id: an identifier will be
// randomly generated by Stripe. You can optionally override this ID",
// https://docs.stripe.com/api/products/create). Subscription items take a
// product id in price_data.product, not product_data
// (https://docs.stripe.com/api/subscriptions/create, items.price_data).
export const TRIAL_PRODUCTS: Record<CheckoutPlan, { id: string; name: string }> = {
  gold: { id: "repsuites_growth", name: GROWTH.name },
  managed: { id: "repsuites_managed", name: MANAGED.name },
};

const meta = (tenantId: string, plan: CheckoutPlan) => ({
  kind: "plan",
  product: "repsuites",
  tenant_id: tenantId,
  plan,
});

// Step 1: the setup-mode Checkout Session body. `currency` is required in
// setup mode when payment method types are not listed; `customer` makes the
// saved card belong to that customer
// (https://docs.stripe.com/api/checkout/sessions/create: mode, currency,
// customer, setup_intent_data).
export function trialCheckoutBody(o: { tenantId: string; plan: CheckoutPlan; customer: string }) {
  const m = { ...meta(o.tenantId, o.plan), trial: "1", interval: "month" };
  return {
    mode: "setup",
    currency: "gbp",
    customer: o.customer,
    client_reference_id: o.tenantId,
    metadata: m,
    setup_intent_data: { metadata: m },
    custom_text: {
      submit: {
        message: `${TRIAL_PRODUCTS[o.plan].name}, ${money(planPence("month", o.plan))} a month. ${TRIAL_TERMS} Nothing is taken today. Cancel before the trial ends and you pay nothing.`,
      },
    },
    success_url: `${ORIGIN}/api/billing/back?paid=1&trial=1`,
    cancel_url: `${ORIGIN}/pricing`,
  };
}

// Step 2: the POST /v1/subscriptions body
// (https://docs.stripe.com/api/subscriptions/create): customer, items with
// price_data {currency, product, unit_amount, recurring.interval},
// default_payment_method (must belong to the customer), trial_end,
// billing_cycle_anchor (a future timestamp), proration_behavior
// (create_prorations, the default, written out) and metadata.
export function trialSubscriptionBody(o: {
  tenantId: string;
  plan: CheckoutPlan;
  customer: string;
  paymentMethod: string;
  sessionId: string;
  today: string;
}) {
  const t = monthlyTrial(o.today, planPence("month", o.plan));
  return {
    customer: o.customer,
    items: [
      {
        quantity: 1,
        price_data: {
          currency: "gbp",
          product: TRIAL_PRODUCTS[o.plan].id,
          unit_amount: planPence("month", o.plan),
          recurring: { interval: "month" },
        },
      },
    ],
    default_payment_method: o.paymentMethod,
    trial_end: t.trialEnd,
    // A trial ending on the 1st already bills on the 1st; no anchor needed.
    ...(t.anchor ? { billing_cycle_anchor: t.anchor } : {}),
    proration_behavior: "create_prorations",
    metadata: { ...meta(o.tenantId, o.plan), checkout_session: o.sessionId },
  };
}

export async function startTrialCheckout(o: {
  tenantId: string;
  plan: CheckoutPlan;
  email: string;
  customer: string | null;
}): Promise<{ ok: true; url: string } | { ok: false; error: string }> {
  let customer = o.customer;
  if (!customer) {
    const c = await stripe<{ id: string }>(
      "customers",
      { email: o.email, metadata: { product: "repsuites", tenant_id: o.tenantId } },
      "POST",
    );
    if (!c.ok) return c;
    customer = c.data.id;
    // Remember it, so trying again later reuses this customer.
    await serviceWrite("tenant_billing?on_conflict=tenant_id", "", {
      method: "POST",
      headers: { Prefer: "resolution=merge-duplicates" },
      body: {
        tenant_id: o.tenantId,
        stripe_customer_id: customer,
        updated_at: new Date().toISOString(),
      },
    }).catch(() => null);
  }
  const s = await stripe<{ url: string }>(
    "checkout/sessions",
    trialCheckoutBody({ tenantId: o.tenantId, plan: o.plan, customer }),
  );
  return s.ok ? { ok: true, url: s.data.url } : s;
}

async function ensureProduct(plan: CheckoutPlan) {
  const p = TRIAL_PRODUCTS[plan];
  const got = await stripe(`products/${p.id}`);
  if (got.ok) return;
  // Not there yet: make it. If two trials race, the second create fails and
  // the subscription below still finds the product.
  await stripe("products", { id: p.id, name: p.name, metadata: { product: "repsuites" } }, "POST");
}

// Step 2, from the webhook. Returns the new subscription, or null when the
// session is not a RepSuites trial or something is missing.
export async function startTrialFromSession(
  session: any,
  today = londonToday(),
): Promise<{ ok: true; sub: any } | { ok: false; error: string } | null> {
  const m = session?.metadata ?? {};
  if (session?.mode !== "setup" || m.kind !== "plan" || m.trial !== "1") return null;
  if (m.product && m.product !== "repsuites") return null;
  const tenantId = String(m.tenant_id ?? "");
  const plan = String(m.plan ?? "") as CheckoutPlan;
  if (!/^[0-9a-f-]{36}$/i.test(tenantId) || !(plan in TRIAL_PRODUCTS)) return null;
  const customer = typeof session.customer === "string" ? session.customer : session.customer?.id;
  const siId =
    typeof session.setup_intent === "string" ? session.setup_intent : session.setup_intent?.id;
  if (!customer || !siId) return { ok: false, error: "No customer or card on the session." };

  // The saved card (https://docs.stripe.com/api/setup_intents/retrieve).
  const si = await stripe<{ payment_method: string | { id: string } | null }>(
    `setup_intents/${siId}`,
  );
  if (!si.ok) return si;
  const pm = si.data.payment_method;
  const paymentMethod = typeof pm === "string" ? pm : pm?.id;
  if (!paymentMethod) return { ok: false, error: "No card was saved." };

  await ensureProduct(plan);
  const sub = await stripe(
    "subscriptions",
    trialSubscriptionBody({
      tenantId,
      plan,
      customer,
      paymentMethod,
      sessionId: String(session.id),
      today,
    }),
    "POST",
    // One subscription per Checkout Session, even if the webhook runs twice.
    { idempotencyKey: `repsuites-trial-${String(session.id)}` },
  );
  return sub.ok ? { ok: true, sub: sub.data } : sub;
}
